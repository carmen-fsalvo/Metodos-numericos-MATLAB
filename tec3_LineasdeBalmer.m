    0, 0, 1;      % Azul
    0, 1, 1;      % Cian
    0, 1, 0;      % Verde
    1, 1, 0;      % Amarillo
    1, 0.5, 0;    % Naranja
    1, 0, 0;      % Rojo
];

% Rangos de longitudes de onda asociados a colores
rangos_colores = [380, 450;  % Violeta
                  450, 495;  % Azul
                  495, 570;  % Verde
                  570, 590;  % Amarillo
                  590, 620;  % Naranja
                  620, 750]; % Rojo

% Crear colores para cada punto de datos
color_puntos = zeros(length(longitud_onda), 3); % Inicialización
for i = 1:length(longitud_onda)
    for j = 1:size(rangos_colores, 1)
        if longitud_onda(i) >= rangos_colores(j, 1) && longitud_onda(i) <= rangos_colores(j, 2)
            color_puntos(i, :) = colores_rgb(j, :);
            break;
        end
    end
end

% Crear la gráfica
figure;
scatter(longitud_onda, intensidad, 25, color_puntos, 'filled'); % Tamaño 25, colores según longitud
xlabel('Longitud de Onda (nm)');
ylabel('Intensidad (counts)');
title('Longitud de Onda vs Intensidad');

% Añadir una leyenda para los colores
hold on;
for j = 1:size(rangos_colores, 1)
    scatter(NaN, NaN, 50, colores_rgb(j, :), 'filled', 'DisplayName', ...
            sprintf('%d-%d nm', rangos_colores(j, 1), rangos_colores(j, 2)));
end
legend('show', 'Location', 'northwest');
grid on;
hold off;




